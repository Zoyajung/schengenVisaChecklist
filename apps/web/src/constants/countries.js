const regionNames =
  typeof Intl !== 'undefined' && Intl.DisplayNames
    ? new Intl.DisplayNames(['en'], {type: 'region'})
    : null

function nameFromCode(code) {
  return COUNTRY_NAME_OVERRIDES[code] || regionNames?.of(code) || code
}

function slugify(value) {
  return String(value || '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

export const COUNTRY_OPTIONS = [
  ...COUNTRY_CODES.map((isoCode) => {
    const name = nameFromCode(isoCode)
    return {isoCode, name, slug: slugify(name)}
  }),
  {isoCode: 'XK', name: 'Kosovo', slug: 'kosovo'},
].sort((a, b) => a.name.localeCompare(b.name))

export const SCHENGEN_COUNTRY_SLUGS = new Set(
  COUNTRY_OPTIONS.filter((country) => SCHENGEN_COUNTRY_CODES.includes(country.isoCode)).map((country) => country.slug),
)
